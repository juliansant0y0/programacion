#Operadores de Pertenencia

a = [1,2,3,4,5]    # lista
  
#Esta 3 en la lista a?
print (3 in a) 
  
#No está 12 en la lista a?
print (12 not in a) 
  
str = "Hello World"
  
#Contiene World el string str?
print ("World" in str) 
  
#Contiene world el string str? (nota: distingue mayúsculas y minúsculas)
print ("world" in str) 

print ("code" not in str) 
